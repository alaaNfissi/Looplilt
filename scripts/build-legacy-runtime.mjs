import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=fileURLToPath(new URL('../',import.meta.url));
async function source(file){return (await fs.readFile(path.join(root,file),'utf8')).replace(/^import .*;\r?\n/gm,'').replace(/^export /gm,'');}
export async function generateLegacyRuntime({check=false}={}){
 const frame=(await Promise.all(['lib/motion.mjs','lib/legacy-frame.mjs'].map(source))).join('\n')+`
let legacyData, legacyCanvas;
self.onmessage=({data:message})=>{
 try{
  if(message.type==='initialize'){legacyData=message.project;legacyCanvas=new OffscreenCanvas(message.width,message.height);self.postMessage({id:message.id,ready:true});}
  else if(message.type==='frame'){const time=renderLegacyFrame(legacyCanvas,legacyData,userDrawing,message.time,{motion,sceneAt,cueTime});const image=legacyCanvas.transferToImageBitmap();self.postMessage({id:message.id,image,time,width:image.width,height:image.height},[image]);}
  else throw new Error('Unknown legacy frame request');
 }catch(error){self.postMessage({id:message.id,error:String(error.message??error).slice(0,1000)});}
};
`;
 const audio=(await Promise.all(['lib/pcm.mjs','lib/studio-sound.mjs','lib/synth.mjs','lib/music.mjs'].map(source))).join('\n')+`
let legacyData;
self.onmessage=({data:message})=>{
 try{
  if(message.type==='initialize'){legacyData=message.project;self.postMessage({id:message.id,ready:true});}
  else if(message.type==='sound'){const bytes=makePcmSound({...legacyData,score:scoreFor(legacyData)},48000);self.postMessage({id:message.id,bytes:bytes.buffer},[bytes.buffer]);}
  else throw new Error('Unknown score request');
 }catch(error){self.postMessage({id:message.id,error:String(error.message??error).slice(0,1000)});}
};
`;
 const digest=createHash('sha256').update(frame).update('\0').update(audio).digest('hex');
 const contents='// Generated by scripts/build-legacy-runtime.mjs from the maintained Looplilt render/audio sources.\n'+`export const legacyRuntimeDigest=${JSON.stringify(digest)};\nexport const legacyFrameRuntime=${JSON.stringify(frame)};\nexport const legacyAudioRuntime=${JSON.stringify(audio)};\n`;
 const file=path.join(root,'lib/graph/legacy-runtime.generated.mjs');
 if(check){if(await fs.readFile(file,'utf8')!==contents)throw new Error('Regenerate the legacy worker runtime before building Studio');}
 else await fs.writeFile(file,contents);
 return {digest,bytes:Buffer.byteLength(contents)};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))console.log(JSON.stringify(await generateLegacyRuntime({check:process.argv.includes('--check')})));
